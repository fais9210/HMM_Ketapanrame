// Helper function to standardize attribute node IDs
export function getAttributeNodeId(category: string, value: string): string {
  return `attr_${category.toLowerCase().replace(/\s+/g, '_')}_${value.toLowerCase().replace(/[^a-z0-9]/g, '_')}`;
}

// Helper to generate all Edges (Codes and Value)
export function generateEdges(): GraphEdge[] {
  const edges: GraphEdge[] = [];
  let edgeCounter = 1;

  // 1. Attribute Edges (Value connections)
  informantsData.forEach((inf) => {
    // Gender
    edges.push({
      id: `edge_attr_${edgeCounter++}`,
      source: inf.id,
      target: getAttributeNodeId('gender', inf.gender),
      type: 'Value',
      label: 'Gender',
      weight: 1,
    });
    // Umur
    edges.push({
      id: `edge_attr_${edgeCounter++}`,
      source: inf.id,
      target: getAttributeNodeId('umur', inf.ageGroup),
      type: 'Value',
      label: 'Umur',
      weight: 1,
    });
    // Peran
    edges.push({
      id: `edge_attr_${edgeCounter++}`,
      source: inf.id,
      target: getAttributeNodeId('peran', inf.role),
      type: 'Value',
      label: 'Peran',
      weight: 1,
    });
    // Pendidikan
    edges.push({
      id: `edge_attr_${edgeCounter++}`,
      source: inf.id,
      target: getAttributeNodeId('pendidikan', inf.education),
      type: 'Value',
      label: 'Jenjang Pendidikan',
      weight: 1,
    });
  });

  // 2. Coded Theme Edges (Codes connections for cell value = 1)
  crosstabMatrixData
    .filter((row) => row.category === 'theme')
    .forEach((row) => {
      Object.entries(row.informants).forEach(([infId, val]) => {
        if (val === 1) {
          edges.push({
            id: `edge_code_${edgeCounter++}`,
            source: infId,
            target: row.nodeId,
            type: 'Codes',
            label: 'Codes',
            weight: 1,
          });
        }
      });
    });

  return edges;
}

